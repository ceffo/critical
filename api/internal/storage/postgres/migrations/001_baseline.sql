-- The PostgreSQL baseline (ADR 0025 step 2): the schema the 33 SQLite migrations built, as one
-- schema-only file. No INSERT, UPDATE or DELETE here or in any later migration (step 2.1): data
-- comes from the seeds and the catalogue import at boot, existing data from the copy tool.
--
-- Types: ids are identity columns (BY DEFAULT: the undo restores of saved buffs and XP entries
-- write a row back under its old id), integers are BIGINT (the Go side reads int64 as it did on
-- SQLite), timestamps TIMESTAMPTZ. The 0/1 flags (two_handed, target_ac_known, bonus) stay
-- integers with their CHECK, and JSON stays TEXT: the Go code encodes, decodes and compares them,
-- no query reads inside them, and the copy tool moves them as they are.

CREATE TABLE characters (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT   NOT NULL,
    str                 BIGINT NOT NULL,
    dex                 BIGINT NOT NULL,
    con                 BIGINT NOT NULL,
    int                 BIGINT NOT NULL,
    wis                 BIGINT NOT NULL,
    cha                 BIGINT NOT NULL,
    hp_max              BIGINT NOT NULL,
    thac0_base          BIGINT NOT NULL,
    level               BIGINT NOT NULL DEFAULT 1,
    xp_total            BIGINT NOT NULL DEFAULT 0,
    save_para_poison    BIGINT NOT NULL DEFAULT 14,
    save_rod_staff_wand BIGINT NOT NULL DEFAULT 14,
    save_petri_poly     BIGINT NOT NULL DEFAULT 14,
    save_breath         BIGINT NOT NULL DEFAULT 14,
    save_spell          BIGINT NOT NULL DEFAULT 14,
    class               TEXT   NOT NULL DEFAULT 'bard',
    race                TEXT   NOT NULL DEFAULT '',
    alignment           TEXT   NOT NULL DEFAULT '',
    age                 BIGINT NOT NULL DEFAULT 0,
    sex                 TEXT   NOT NULL DEFAULT '',
    height              TEXT   NOT NULL DEFAULT '',
    weight              TEXT   NOT NULL DEFAULT '',
    hair                TEXT   NOT NULL DEFAULT '',
    eyes                TEXT   NOT NULL DEFAULT '',
    languages           TEXT   NOT NULL DEFAULT '[]'
);

CREATE TABLE hp_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id BIGINT      NOT NULL REFERENCES characters(id),
    delta        BIGINT      NOT NULL,
    source       TEXT        NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE active_buffs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id BIGINT NOT NULL REFERENCES characters(id),
    buffs        TEXT   NOT NULL DEFAULT '[]'
);
CREATE UNIQUE INDEX idx_active_buffs_character_id ON active_buffs(character_id);

CREATE TABLE spell_slots (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id BIGINT NOT NULL REFERENCES characters(id),
    slots        TEXT   NOT NULL DEFAULT '{}'
);
CREATE UNIQUE INDEX idx_spell_slots_character_id ON spell_slots(character_id);

CREATE TABLE action_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id   BIGINT      NOT NULL REFERENCES characters(id),
    round          BIGINT      NOT NULL DEFAULT 0,
    kind           TEXT        NOT NULL,
    summary        TEXT        NOT NULL,
    hp_delta       BIGINT      NOT NULL DEFAULT 0,
    payload        TEXT        NOT NULL DEFAULT '{}',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    transaction_id BIGINT REFERENCES action_log(id)
);
CREATE INDEX idx_action_log_character ON action_log(character_id, id);
CREATE INDEX idx_action_log_transaction ON action_log(character_id, transaction_id, id);

CREATE TABLE round_state (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id        BIGINT NOT NULL REFERENCES characters(id),
    round_number        BIGINT NOT NULL DEFAULT 0,
    initiative_d10      BIGINT,
    initiative_entry_id BIGINT
);
CREATE UNIQUE INDEX idx_round_state_character_id ON round_state(character_id);

CREATE TABLE action_snapshots (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_id    BIGINT NOT NULL REFERENCES action_log(id),
    state_key    TEXT   NOT NULL,
    before_state TEXT   NOT NULL,
    after_state  TEXT   NOT NULL,
    UNIQUE (action_id, state_key)
);
CREATE INDEX idx_action_snapshots_key ON action_snapshots(state_key, action_id);

CREATE TABLE action_corrections (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_id  BIGINT      NOT NULL REFERENCES action_log(id),
    kind       TEXT        NOT NULL CHECK (kind IN ('amend', 'void', 'redo')),
    hp_delta   BIGINT,
    summary    TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    payload    TEXT,
    note       TEXT,
    step_id    BIGINT REFERENCES action_log(id)
);
CREATE INDEX idx_action_corrections_action ON action_corrections(action_id, id);

CREATE TABLE crit_table_rows (
    roll_from  BIGINT PRIMARY KEY CHECK (roll_from BETWEEN 1 AND 100),
    roll_to    BIGINT NOT NULL CHECK (roll_to BETWEEN 1 AND 100 AND roll_to >= roll_from),
    multiplier DOUBLE PRECISION NOT NULL CHECK (multiplier >= 1)
);

CREATE TABLE saved_buffs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id BIGINT      NOT NULL REFERENCES characters(id),
    name         TEXT        NOT NULL,
    duration     BIGINT      NOT NULL DEFAULT 0 CHECK (duration >= 0),
    charges      BIGINT      NOT NULL DEFAULT 0 CHECK (charges >= 0),
    effects      TEXT        NOT NULL DEFAULT '{}',
    note         TEXT        NOT NULL DEFAULT '',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_saved_buffs_character ON saved_buffs(character_id, id);

CREATE TABLE attack_forms (
    character_id       BIGINT PRIMARY KEY REFERENCES characters(id),
    weapon_id          TEXT   NOT NULL DEFAULT '',
    previous_weapon_id TEXT   NOT NULL DEFAULT '',
    ammo_item_id       TEXT   NOT NULL DEFAULT '',
    target_ac          BIGINT NOT NULL DEFAULT 5,
    target_size        TEXT   NOT NULL DEFAULT 'sm' CHECK (target_size IN ('sm', 'l')),
    situational_value  BIGINT NOT NULL DEFAULT 0,
    situational_label  TEXT   NOT NULL DEFAULT '',
    target_ac_known    BIGINT NOT NULL DEFAULT 0 CHECK (target_ac_known IN (0, 1))
);

CREATE TABLE xp_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id BIGINT NOT NULL REFERENCES characters(id),
    entry_date   TEXT   NOT NULL,
    session      TEXT   NOT NULL DEFAULT '',
    reason       TEXT   NOT NULL DEFAULT '',
    base         BIGINT NOT NULL CHECK (base > 0),
    bonus        BIGINT NOT NULL DEFAULT 0 CHECK (bonus IN (0, 1))
);
CREATE INDEX xp_entries_character ON xp_entries (character_id, id);

CREATE TABLE proficiencies (
    id       TEXT   PRIMARY KEY,
    position BIGINT NOT NULL,
    ability  TEXT   NOT NULL CHECK (ability IN ('str', 'dex', 'con', 'int', 'wis', 'cha')),
    modifier BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE bard_skills (
    id       TEXT   PRIMARY KEY,
    position BIGINT NOT NULL,
    percent  BIGINT NOT NULL CHECK (percent BETWEEN 0 AND 100)
);

CREATE TABLE dice_favourites (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id BIGINT NOT NULL REFERENCES characters(id),
    formula      TEXT   NOT NULL,
    position     BIGINT NOT NULL DEFAULT 0,
    UNIQUE (character_id, formula)
);

CREATE TABLE catalogue_meta (
    id      BIGINT PRIMARY KEY CHECK (id = 1),
    format  BIGINT NOT NULL,
    version TEXT   NOT NULL
);

CREATE TABLE localized_texts (
    text_id BIGINT NOT NULL,
    lang    TEXT   NOT NULL,
    body    TEXT   NOT NULL CHECK (body <> ''),
    PRIMARY KEY (text_id, lang)
);

CREATE TABLE spells (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key            TEXT,
    name           BIGINT,
    class          TEXT   NOT NULL,
    level          BIGINT NOT NULL,
    school         BIGINT,
    sphere         BIGINT,
    casting_time   BIGINT,
    range          BIGINT,
    duration       BIGINT,
    area_of_effect BIGINT,
    components     BIGINT,
    saving_throw   BIGINT,
    description    BIGINT,
    source         TEXT,
    stats          TEXT
);
CREATE UNIQUE INDEX idx_spells_key ON spells(key);

CREATE TABLE items (
    id          TEXT   PRIMARY KEY,
    position    BIGINT NOT NULL,
    name        BIGINT NOT NULL,
    type        TEXT   NOT NULL DEFAULT '',
    behaviour   TEXT   NOT NULL CHECK (behaviour IN ('stock', 'charges', 'daily')),
    magic_bonus BIGINT NOT NULL DEFAULT 0,
    ammo_kind   TEXT   NOT NULL DEFAULT '',
    count       BIGINT NOT NULL CHECK (count >= 0),
    max_count   BIGINT NOT NULL CHECK (max_count >= 0),
    effect_dice TEXT   NOT NULL DEFAULT '',
    effect_save TEXT   NOT NULL DEFAULT '',
    notes       TEXT   NOT NULL DEFAULT '',
    powers      TEXT   NOT NULL DEFAULT '[]'
);

CREATE TABLE weapons (
    id           TEXT   PRIMARY KEY,
    position     BIGINT NOT NULL,
    name         BIGINT NOT NULL,
    damage_sm    TEXT   NOT NULL,
    damage_l     TEXT   NOT NULL,
    magic_to_hit BIGINT NOT NULL DEFAULT 0,
    magic_damage BIGINT NOT NULL DEFAULT 0,
    kind         TEXT   NOT NULL CHECK (kind IN ('melee', 'missile')),
    two_handed   BIGINT NOT NULL DEFAULT 0 CHECK (two_handed IN (0, 1)),
    ammo_kind    TEXT   NOT NULL DEFAULT ''
);

CREATE TABLE seeded_name_languages (
    kind TEXT NOT NULL CHECK (kind IN ('item', 'weapon')),
    id   TEXT NOT NULL,
    lang TEXT NOT NULL,
    PRIMARY KEY (kind, id, lang)
);
