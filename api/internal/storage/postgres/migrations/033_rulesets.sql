-- The ruleset (ADR 0041): which book data and which house rules a game is played with. The house
-- rules are a typed record: the racial lift and the level limits mode are columns, the crit table
-- and the success effects child rows, the edits an append-only audit.
--
-- This file is the schema only (ADR 0025 step 2.1). Its data step, run right after it
-- (defaultRuleset), creates the default ruleset, copies the stored crit_table_rows into the
-- default's crit rows (an edited table is kept; none stored means the placeholder default) and
-- seeds the Tumbling success effect. crit_table_rows stays as the legacy table the copy reads:
-- nothing reads or writes it afterwards.
--
-- Additive (ADR 0024 step 5.2, ADR 0025 step 2.2): the release before this one reads and writes
-- crit_table_rows only, which is left as it is.
CREATE TABLE rulesets (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT    NOT NULL UNIQUE CHECK (name <> ''),
    -- The catalogue version the ruleset reads: recorded, not enforced.
    catalogue_version   TEXT    NOT NULL DEFAULT '',
    -- True until an admin saves a crit table: the rows are then the default table.
    crit_placeholder    BOOLEAN NOT NULL DEFAULT FALSE,
    multiclass_any_race BOOLEAN NOT NULL DEFAULT TRUE,
    dualclass_any_race  BOOLEAN NOT NULL DEFAULT TRUE,
    level_limits        TEXT    NOT NULL DEFAULT 'warn' CHECK (level_limits IN ('warn'))
);

CREATE TABLE ruleset_crit_rows (
    ruleset_id BIGINT           NOT NULL REFERENCES rulesets(id),
    roll_from  BIGINT           NOT NULL CHECK (roll_from BETWEEN 1 AND 100),
    roll_to    BIGINT           NOT NULL CHECK (roll_to BETWEEN 1 AND 100 AND roll_to >= roll_from),
    multiplier DOUBLE PRECISION NOT NULL CHECK (multiplier >= 1),
    PRIMARY KEY (ruleset_id, roll_from)
);

CREATE TABLE ruleset_success_effects (
    ruleset_id     BIGINT NOT NULL REFERENCES rulesets(id),
    proficiency_id TEXT   NOT NULL CHECK (proficiency_id <> ''),
    ac             BIGINT NOT NULL,
    rounds         BIGINT NOT NULL CHECK (rounds >= 1),
    PRIMARY KEY (ruleset_id, proficiency_id)
);

CREATE TABLE ruleset_changes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruleset_id   BIGINT      NOT NULL REFERENCES rulesets(id),
    changed_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    changed_by   UUID        NOT NULL REFERENCES users(id),
    rule         TEXT        NOT NULL CHECK (rule <> ''),
    before_value TEXT        NOT NULL,
    after_value  TEXT        NOT NULL
);
CREATE INDEX idx_ruleset_changes_ruleset ON ruleset_changes(ruleset_id, id);
