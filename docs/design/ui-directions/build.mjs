// Builds the design-direction pages: one HTML file per direction and activity, the logo page,
// the logo SVG files and shared/tokens.css (the palette blocks copied from web/src/index.css, so
// the pages use the app's real theme tokens). Run from the repo root: `node docs/design/ui-directions/build.mjs`
// (or `just design-shots`, which also screenshots them). No dependencies.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as ui from "./lib/ui.mjs";
import { logos, logoFile } from "./lib/logos.mjs";
import { logoPage } from "./lib/logo-page.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../../..");

/** The `:root` and `.dark` palette blocks of index.css, as `.theme-light` / `.theme-dark`. */
function tokensCss() {
  const css = readFileSync(path.join(root, "web/src/index.css"), "utf8");
  const block = (selector) => {
    const m = css.match(new RegExp(`^${selector.replace(".", "\\.")} \\{\\n([\\s\\S]*?)^\\}`, "m"));
    if (!m) throw new Error(`index.css: no ${selector} block`);
    return m[1];
  };
  return `/* Generated by build.mjs from web/src/index.css (ADR 0020 tokens): do not edit. */
.theme-light {
${block(":root")}}
.theme-dark {
${block(".dark")}}
.theme-light, .theme-dark {
  --ink-muted: color-mix(in oklab, var(--ink) 70%, transparent);
  --border: color-mix(in oklab, var(--ink) 18%, transparent);
  --input: color-mix(in oklab, var(--ink) 22%, transparent);
}
`;
}

export const directions = await Promise.all(
  ["a2", "a3", "b"].map((x) => import(`./lib/direction-${x}.mjs`)),
);

export function build() {
  mkdirSync(path.join(here, "shared"), { recursive: true });
  writeFileSync(path.join(here, "shared/tokens.css"), tokensCss());
  const built = [];
  for (const dir of directions) {
    const out = path.join(here, dir.id);
    mkdirSync(out, { recursive: true });
    writeFileSync(path.join(out, dir.css), dir.stylesheet);
    for (const [pageId, render] of Object.entries(dir.pages)) {
      const file = path.join(out, `${pageId}.html`);
      writeFileSync(
        file,
        ui.page({ title: `${dir.name} · ${pageId}`, css: dir.css, body: render() }),
      );
      built.push(file);
    }
  }
  const logoDir = path.join(here, "logo");
  mkdirSync(logoDir, { recursive: true });
  for (const id of Object.keys(logos)) writeFileSync(path.join(logoDir, `${id}.svg`), logoFile(id));
  const logoFile_ = path.join(logoDir, "index.html");
  writeFileSync(logoFile_, logoPage());
  built.push(logoFile_);
  return built;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const f of build()) console.log(path.relative(root, f));
}
